@RunWith(AndroidJUnit4::class)
class PlaybackIntegrationTest {
 private val instrumentation=InstrumentationRegistry.getInstrumentation()
 private val context=instrumentation.targetContext
 private fun ui(block: () -> Unit) = instrumentation.runOnMainSync(block)
 private fun await(message: String, condition: () -> Boolean) {
  val until=System.currentTimeMillis()+15000
  while(System.currentTimeMillis()<until) {var satisfied=false; ui {satisfied=condition()};if(satisfied)return;Thread.sleep(100)}
  fail(message)
 }
 private fun sample(name: String): Uri {
  val file=File(context.cacheDir,name)
  instrumentation.context.assets.open(name).use {source->file.outputStream().use {source.copyTo(it)}}
  return Uri.fromFile(file)
 }
 private fun shell(command: String) { instrumentation.uiAutomation.executeShellCommand(command).use { android.os.ParcelFileDescriptor.AutoCloseInputStream(it).readBytes() } }
 private fun screenshot(name: String) {
  val folder=File(context.filesDir,"test-artifacts").apply {mkdirs()}
  instrumentation.uiAutomation.takeScreenshot()?.let {bitmap->File(folder,"$name.png").outputStream().use {bitmap.compress(android.graphics.Bitmap.CompressFormat.PNG,100,it)};bitmap.recycle()}
 }
 private fun validateProjectionOrientation(c: PlaybackController) {
  val location=IntArray(2);var width=0;var height=0
  ui {val view=c.panorama!!;view.getLocationOnScreen(location);width=view.width;height=view.height}
  val bitmap=instrumentation.uiAutomation.takeScreenshot()!!
  try {
   fun greenAt(fraction: Float): Double {
    val samples=mutableListOf<Int>()
    for(dx in 22..35 step 2) for(dy in -2..2) {
     val color=bitmap.getPixel(location[0]+width*dx/100,location[1]+(height*fraction).toInt()+dy*4)
     if(android.graphics.Color.blue(color)<180) samples.add(android.graphics.Color.green(color))
    }
    assertTrue("visible projected colors",samples.isNotEmpty());return samples.average()
   }
   assertTrue("source upper hemisphere must remain above lower hemisphere",greenAt(.25f)-greenAt(.75f)>60)
  } finally {bitmap.recycle()}
 }
