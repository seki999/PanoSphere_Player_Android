 @Test fun gesturesAndStereoEyeExtraction() {
  shell("input keyevent KEYCODE_WAKEUP");shell("wm dismiss-keyguard")
  val activity=instrumentation.startActivitySync(Intent(context,MainActivity::class.java).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)) as MainActivity
  val c=activity.controller
  try {
   val uri=sample("sbs-fisheye-180.mp4")
   ui {c.import(listOf(uri))}
   await("stereo sample plays") {c.current?.name=="sbs-fisheye-180.mp4" && c.playing}
   ui {c.changeMode(PlaybackMode.FISHEYE_180);c.update {copy(eye=1)};c.repeatMode=androidx.media3.common.Player.REPEAT_MODE_ONE}
   await("GL view attached") {c.panorama?.width?.let {it>0}==true}
   Thread.sleep(500)
   fun redMinusBlue(): Double {
    val xy=IntArray(2);var w=0;var h=0
    ui {c.panorama!!.let {it.getLocationOnScreen(xy);w=it.width;h=it.height}}
    val b=instrumentation.uiAutomation.takeScreenshot()!!
    return try {(22..35).flatMap {x->(22..27).map {y->b.getPixel(xy[0]+w*x/100,xy[1]+h*y/100)}}.filter {android.graphics.Color.green(it)<220}.map {(android.graphics.Color.red(it)-android.graphics.Color.blue(it)).toDouble()}.average()} finally {b.recycle()}
   }
   val left=redMinusBlue()
   ui {c.update {copy(eye=2)}};Thread.sleep(300)
   val right=redMinusBlue();assertTrue("SBS eye must select different half texture",left-right>100)
   screenshot("stereo-right-eye")
   ui {
    val view=c.panorama!!;val t=android.os.SystemClock.uptimeMillis();val x=view.width/2f;val y=view.height/2f
    fun touch(action: Int,xx: Float,yy: Float,delta: Long) {val e=android.view.MotionEvent.obtain(t,t+delta,action,xx,yy,0);view.dispatchTouchEvent(e);e.recycle()}
    touch(android.view.MotionEvent.ACTION_DOWN,x,y-200,0);touch(android.view.MotionEvent.ACTION_MOVE,x+200,y-200,50);touch(android.view.MotionEvent.ACTION_UP,x+200,y-200,100)
    view.reset()
    val before=view.fov
    touch(android.view.MotionEvent.ACTION_DOWN,x-200,y-200,200)
    fun multi(action: Int,span: Float,delta: Long) {
     val properties=Array(2) {index->android.view.MotionEvent.PointerProperties().apply {id=index;toolType=android.view.MotionEvent.TOOL_TYPE_FINGER}}
     val coords=Array(2) {index->android.view.MotionEvent.PointerCoords().apply {this.x=x+(if(index==0)-span else span);this.y=y-200;pressure=1f;size=1f}}
     val e=android.view.MotionEvent.obtain(t,t+delta,action,2,properties,coords,0,0,1f,1f,0,0,android.view.InputDevice.SOURCE_TOUCHSCREEN,0);view.dispatchTouchEvent(e);e.recycle()
    }
    multi(android.view.MotionEvent.ACTION_POINTER_DOWN or (1 shl android.view.MotionEvent.ACTION_POINTER_INDEX_SHIFT),200f,220)
    multi(android.view.MotionEvent.ACTION_MOVE,300f,260);multi(android.view.MotionEvent.ACTION_MOVE,420f,300)
    multi(android.view.MotionEvent.ACTION_POINTER_UP or (1 shl android.view.MotionEvent.ACTION_POINTER_INDEX_SHIFT),420f,340)
    touch(android.view.MotionEvent.ACTION_UP,x-420,y-200,360)
    assertTrue("pinch changes FOV",view.fov<before);assertEquals(view.fov,c.current!!.fov)
    c.changeMode(PlaybackMode.FLAT)
   }
   Thread.sleep(300)
   repeat(8) {ui {c.changeMode(if(it%2==0) PlaybackMode.EQUIRECT_360 else PlaybackMode.FLAT)};Thread.sleep(100)}
   ui {assertNull(c.error);assertTrue(c.playing)}
  } finally {ui {c.stop();activity.finish()}}
 }}









